// Writes src/capitals.js: one capital per map unit ([lon, lat, English name]), where searching for a country flies to.
// Source: Natural Earth 1:10m populated places (public domain); the dependencies it leaves out are filled in by hand below.
// Units with no capital (Antarctica, bases, uninhabited islands) are left out, and the page falls back to the largest polygon.
// Usage: node scripts/capitals.mjs (after build.sh; reads work/names.json and raw/ne_10m_populated_places_simple)
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url'; import { execFileSync } from 'child_process';
const R = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), W = R + '/work';
execFileSync('node', [R + '/node_modules/mapshaper/bin/mapshaper', '-i', R + '/raw/ne_10m_populated_places_simple/ne_10m_populated_places_simple.shp',
  '-filter', "/capital/.test(featurecla)", '-filter-fields', 'name,adm0_a3,featurecla,adm0cap,capalt,pop_max,longitude,latitude', '-o', W + '/capitals.json', 'format=json'], { stdio: 'ignore' });
const rows = JSON.parse(fs.readFileSync(W + '/capitals.json')), names = JSON.parse(fs.readFileSync(W + '/names.json'));
// Natural Earth codes that differ from the unit ids
const ALIAS = { SSD: 'SDS' };
// where a country has more than one capital, the constitutional one; Palestine's seat of government
const PICK = { ZAF: 'Pretoria', BOL: 'Sucre', CIV: 'Yamoussoukro', TZA: 'Dodoma', BEN: 'Porto-Novo', LKA: 'Sri Jayawardenepura Kotte', PSX: 'Ramallah' };
// capitals missing from Natural Earth; Western Sahara goes to its largest town, as it gets no flag either (scripts/flags.mjs)
const HAND = {
  SAH: [-13.2, 27.15, 'Laayoune'],
  MAF: [-63.083, 18.068, 'Marigot'], SXM: [-63.045, 18.026, 'Philipsburg'], SPM: [-56.177, 46.778, 'Saint-Pierre'],
  PCN: [-130.101, -25.067, 'Adamstown'], MSR: [-62.211, 16.792, 'Brades'], VIR: [-64.931, 18.342, 'Charlotte Amalie'],
  BLM: [-62.849, 17.896, 'Gustavia'], AIA: [-63.057, 18.217, 'The Valley'], VGB: [-64.620, 18.427, 'Road Town'],
  SHN: [-5.717, -15.925, 'Jamestown'], JEY: [-2.107, 49.186, 'Saint Helier'], GGY: [-2.536, 49.455, 'Saint Peter Port'],
  NFK: [167.960, -29.056, 'Kingston'], WLF: [-176.174, -13.282, 'Mata-Utu'], NRU: [166.921, -0.547, 'Yaren'],
  IOA: [105.678, -10.427, 'Flying Fish Cove'], IOT: [72.411, -7.313, 'Diego Garcia'], ATF: [70.219, -49.351, 'Port-aux-Français']
};
// Admin-0 capitals first, then the capitals of dependencies, then first-level capitals (the Faroes, Puerto Rico …)
const rank = r => r.featurecla === 'Admin-0 capital' && r.adm0cap === 1 && !r.capalt ? 0 : r.featurecla === 'Admin-0 capital' ? 1
  : r.featurecla === 'Admin-0 region capital' ? 2 : r.featurecla === 'Admin-0 capital alt' ? 3 : 4;
const out = {}, none = [];
for (const [id] of names) {
  if (HAND[id]) { out[id] = HAND[id]; continue; }
  const own = rows.filter(r => (ALIAS[r.adm0_a3] || r.adm0_a3) === id);
  const r = own.find(r => r.name === PICK[id]) || own.sort((a, b) => rank(a) - rank(b) || b.pop_max - a.pop_max)[0];
  if (r) out[id] = [+r.longitude.toFixed(3), +r.latitude.toFixed(3), r.name.replace(/\s+/g, ' ')];
  else none.push(id);
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`).join(',\n');
fs.writeFileSync(R + '/src/capitals.js', `// Generated by scripts/capitals.mjs: the capital of each map unit, [lon, lat, name], from Natural Earth (public domain).
const CAPITALS = {
${body}
};
`);
console.log('capitals', Object.keys(out).length, 'none', none.join(' '));
